    objective: str = ""
    recommendation: Optional[Dict[str, Any]] = None
    action_type: Optional[str] = None
    human_decision: Optional[str] = None  # NONE, APPROVED, MODIFIED, OVERRIDDEN, HALTED, ESCALATED
